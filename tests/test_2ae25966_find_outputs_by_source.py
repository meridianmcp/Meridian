@pytest.mark.asyncio
async def test_find_outputs_by_source_dispatches_end_to_end(tmp_path):
    from meridian import server as srv

    _write(
        tmp_path / "metrics.csv",
        "# generated by analysis/train.py\naccuracy,loss\n0.9,0.1\n",
    )
    _write(
        tmp_path / "unrelated.csv",
        "# generated by other_thing.py\nx,y\n1,2\n",
    )

    result = await srv._dispatch_mcp_tool(
        "find_outputs_by_source",
        {"outputs_dir": str(tmp_path), "source_path": "analysis/train.py"},
        None, "/tmp",
    )
    assert isinstance(result, dict)
    assert result["source_path"] == "analysis/train.py"
    assert result["total"] == 1
    assert len(result["outputs"]) == 1
    assert result["outputs"][0]["path"].endswith("metrics.csv")
    assert result["outputs"][0]["generating_script"] == "analysis/train.py"


