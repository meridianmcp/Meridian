"""Tests for sprint item 2ae25966 — expose find_outputs_by_source (script/data
source -> outputs it produced) as a CORE MCP tool.

Prior state (confirmed by investigation): find_outputs_by_source already
existed and was already wired as its own ``@mcp.tool()`` in
``extensions/meridian-outputs/meridian_outputs/provenance.py`` /
``server.py`` — but that is the meridian-outputs TUNNEL PLUGIN's own local
MCP server, only reachable by a self-hosted user running ``--tunnel``. It was
never wired into the CORE ``meridian/server.py`` MCP tool catalog that
hosted-tier / no-tunnel clients talk to directly — only the forward
direction (``resolve_figure_output``, folded into ``find_similar_figure``'s
cross-store resolve-through) was reachable there.

This file covers the new core-side wiring end to end, mirroring the existing
``search_outputs`` pattern (5116078b cached incremental index, 0dedff91
hosted-mode guard + 1365e01a tunnel-proxy fallback, mcp_tools.py registration
metadata):

1. ``outputs_indexer.OutputsFtsIndex.find_by_source`` — the reverse SQL scan
   over the recorded ``generating_script`` column (exact + basename tiers).
2. ``outputs_indexer.find_outputs_by_source`` — the stateless, cached-index
   module-level wrapper (mirrors ``resolve_figure_output``/``search_outputs``).
3. MCP tool registration: present + read-only in ``_MCP_TOOLS_LIST`` /
   ``_READ_ONLY_TOOLS``, with the expected required schema fields.
4. End-to-end dispatch via ``server._dispatch_mcp_tool`` on a REAL temp
   outputs tree — proves the new core tool actually returns real
   reverse-lookup results, not just plumbing.
5. Required-arg guards (outputs_dir, source_path).
6. Hosted-mode guard + tunnel-proxy fallback (0dedff91 / 1365e01a), matching
   the same contract already covered for search_outputs/annotate_outputs in
   tests/test_1365e01a_outputs_tunnel_routing.py.
"""
from __future__ import annotations

import asyncio
