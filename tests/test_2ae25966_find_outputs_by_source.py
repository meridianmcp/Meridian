# ---------------------------------------------------------------------------

def test_find_by_source_exact_and_basename_tiers(tmp_path):
    _write(
        tmp_path / "run_a.csv",
        "# generated by analysis/run.py\ntemp,pressure\n300,101\n",
    )
    _write(
        tmp_path / "run_b.json",
        json.dumps({"generated_by": "run.py", "value": 1}),
    )
    _write(
        tmp_path / "unrelated.json",
        json.dumps({"generating_script": "other_script.py", "value": 2}),
    )
    index = oi.OutputsFtsIndex(str(tmp_path))
    index.rebuild(max_seconds=None)

    matches = index.find_by_source("analysis/run.py")
    paths = {os.path.basename(m["path"]) for m in matches}
    # run_a.csv matches via the exact tier (generating_script recorded
    # verbatim as "analysis/run.py"); run_b.json matches via the basename
    # tier (recorded as bare "run.py", same final component).
    assert paths == {"run_a.csv", "run_b.json"}
    assert all(m["generating_script"] for m in matches)


def test_find_by_source_no_match_for_unrelated_source(tmp_path):
    _write(
        tmp_path / "run_a.csv",
        "# generated by generate_baselines.py\nx,y\n1,2\n",
    )
    index = oi.OutputsFtsIndex(str(tmp_path))
    index.rebuild(max_seconds=None)
    assert index.find_by_source("completely_different_script.py") == []


def test_find_by_source_sorts_newest_first_by_mtime(tmp_path):
    older = tmp_path / "older.csv"
    newer = tmp_path / "newer.csv"
    _write(older, "# generated by run.py\nx,y\n1,2\n")
    _write(newer, "# generated by run.py\nx,y\n3,4\n")
    now = time.time()
    os.utime(older, (now - 1000, now - 1000))
    os.utime(newer, (now, now))

    index = oi.OutputsFtsIndex(str(tmp_path))
    index.rebuild(max_seconds=None)
    matches = index.find_by_source("run.py")
    assert [os.path.basename(m["path"]) for m in matches] == [
        "newer.csv", "older.csv",
    ]


def test_find_by_source_blank_source_returns_empty(tmp_path):
    index = oi.OutputsFtsIndex(str(tmp_path))
    index.rebuild(max_seconds=None)
    assert index.find_by_source("") == []
    assert index.find_by_source(None) == []  # type: ignore[arg-type]


