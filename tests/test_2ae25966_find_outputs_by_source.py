def test_module_find_outputs_by_source_roundtrip(tmp_path):
    outputs = str(tmp_path)
    _write(
        tmp_path / "run_a.json",
        json.dumps({
            "generating_script": "width_baseline_generator/generate_baselines.py",
            "width_px": 1.2,
        }),
    )
    _write(
        tmp_path / "run_b.json",
        json.dumps({
            "generating_script": "width_baseline_generator/generate_baselines.py",
            "width_px": 1.3,
        }),
    )
    _write(
        tmp_path / "unrelated.json",
        json.dumps({"generating_script": "other_script.py", "value": 1}),
    )

    result = oi.find_outputs_by_source(
        outputs,
        "C:/Users/dev/project/width_baseline_generator/generate_baselines.py",
    )
    assert result["total"] == 2
    paths = {os.path.basename(o["path"]) for o in result["outputs"]}
    assert paths == {"run_a.json", "run_b.json"}
    assert result["source_path"] == (
        "C:/Users/dev/project/width_baseline_generator/generate_baselines.py"
    )


def test_module_find_outputs_by_source_respects_limit_and_reports_total(tmp_path):
    for i in range(5):
        _write(
            tmp_path / f"run_{i}.csv",
            "# generated by sweep.py\nx,y\n1,2\n",
        )
    result = oi.find_outputs_by_source(str(tmp_path), "sweep.py", limit=2)
    assert result["total"] == 5
    assert len(result["outputs"]) == 2


def test_module_find_outputs_by_source_reuses_cached_index(tmp_path, monkeypatch):
    """Mirrors test_search_outputs_reuses_cached_index_across_calls: repeat
    calls on the same outputs_dir hit the SAME cached, already-populated
    OutputsFtsIndex rather than starting a fresh manifest each time."""
    monkeypatch.setattr(oi, "_index_cache", oi.OrderedDict())
    _write(tmp_path / "run_a.csv", "# generated by run.py\nx,y\n1,2\n")

    r1 = oi.find_outputs_by_source(str(tmp_path), "run.py")
    assert r1["total"] == 1
    key = oi._cache_key(str(tmp_path))
    cached = oi._index_cache[key]

    r2 = oi.find_outputs_by_source(str(tmp_path), "run.py")
    assert oi._index_cache[key] is cached
    assert r2["total"] == 1


