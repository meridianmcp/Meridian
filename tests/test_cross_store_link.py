def test_find_similar_figures_resolves_through_to_output(tmp_path):
    async def _run():
        outputs = _seed_outputs(str(tmp_path / "outputs"))
        canonical = os.path.join(outputs, "scatter.json")
        store = await _open_store(tmp_path)
        idx = oi.OutputsFtsIndex(outputs)
        try:
            idx.rebuild()
            doc = await store.put_document("proj-x", "docx", [], source="thesis.docx")
            # one figure whose file_path IS the indexed output, one that is not
            await store.put_figures(doc["id"], [
                {"file_path": canonical, "caption": "Figure 1: scatter of x vs y"},
                {"file_path": os.path.join(outputs, "unindexed.png"),
                 "caption": "Figure 2: a photo"},
            ])
            matches = await store.find_similar_figures(
                doc["id"], "scatter of x vs y", limit=5,
                output_resolver=idx.resolve_output,
            )
            by_cap = {m["caption"]: m for m in matches}
            linked = by_cap["Figure 1: scatter of x vs y"]["linked_output"]
            assert linked is not None
            assert linked["generating_script"] == "plot_scatter.py"
            assert linked["is_archival"] is False
            # a figure that names no indexed output resolves to None cleanly
            assert by_cap["Figure 2: a photo"]["linked_output"] is None
        finally:
            idx.close()

    asyncio.run(_run())


def test_find_similar_figures_without_resolver_has_no_linked_output(tmp_path):
    async def _run():
        store = await _open_store(tmp_path)
        doc = await store.put_document("proj-x", "docx", [], source="t.docx")
        await store.put_figures(doc["id"], [
            {"file_path": "/o/scatter.json", "caption": "Figure 1: scatter"},
        ])
        matches = await store.find_similar_figures(doc["id"], "scatter", limit=5)
        assert matches
        # No resolver → the cross-store hop is skipped entirely, not None-valued.
        assert "linked_output" not in matches[0]

    asyncio.run(_run())


def test_store_resolve_figure_output_single(tmp_path):
    async def _run():
        outputs = _seed_outputs(str(tmp_path / "outputs"))
        canonical = os.path.join(outputs, "scatter.json")
        store = await _open_store(tmp_path)
        idx = oi.OutputsFtsIndex(outputs)
        try:
            idx.rebuild()
            doc = await store.put_document("proj-x", "docx", [], source="t2.docx")
            await store.put_figures(doc["id"], [
                {"file_path": canonical, "caption": "Figure 1: scatter"},
            ])
            hit = await store.resolve_figure_output(
                doc["id"], canonical, idx.resolve_output,
            )
            assert hit is not None
            assert hit["figure"]["caption"] == "Figure 1: scatter"
            assert hit["linked_output"]["generating_script"] == "plot_scatter.py"
            # no figure at that path → None
            miss = await store.resolve_figure_output(
                doc["id"], os.path.join(outputs, "table.csv"), idx.resolve_output,
            )
            assert miss is None
        finally:
            idx.close()

    asyncio.run(_run())


def test_resolver_that_raises_is_swallowed(tmp_path):
    async def _run():
        store = await _open_store(tmp_path)
        doc = await store.put_document("proj-x", "docx", [], source="t3.docx")
        await store.put_figures(doc["id"], [
            {"file_path": "/o/scatter.json", "caption": "Figure 1: scatter"},
        ])

        def _boom(_path):
            raise RuntimeError("resolver exploded")

        matches = await store.find_similar_figures(
            doc["id"], "scatter", limit=5, output_resolver=_boom,
        )
        # A resolver that raises → linked_output None, never crashes the match.
        assert matches[0]["linked_output"] is None

    asyncio.run(_run())


# ---------------------------------------------------------------------------
# MCP tool surface — find_similar_figure resolves through when given outputs_dir
# ---------------------------------------------------------------------------

def test_mcp_find_similar_figure_resolves_through(tmp_path, monkeypatch):
    async def _run():
        from meridian import server as mh

        outputs = _seed_outputs(str(tmp_path / "outputs"))
        canonical = os.path.join(outputs, "scatter.json")

        # Seed the doc store the handler resolves to (env-scoped sidecar).
        sidecar = str(tmp_path / "mcp_doc_structure.db")
        monkeypatch.setenv("MERIDIAN_DOC_STORE_URL", sidecar)
        doc_store._reset_doc_store_cache()

        db = await db_module.init_db(":memory:")
        try:
            proj = await db_module.create_project(db, "xstore-proj")
            pid = proj["id"]
            seed = await doc_store.open_doc_store_for(
                plan=None, hosted=False, data_dir=str(tmp_path),
                tenant_pg_url=None, override_url=sidecar,
            )
            await seed.put_document(pid, "docx", [], source="paper.docx")
            doc_row = await seed.get_document(pid, "paper.docx")
            await seed.put_figures(doc_row["id"], [
                {"file_path": canonical, "caption": "Figure 1: scatter of x vs y"},
            ])

            # Without outputs_dir → pure fuzzy match, no linked_output key.
            plain = await mh._dispatch_mcp_tool(
                "find_similar_figure",
                {"project_id": pid, "doc": "paper.docx",
                 "description_or_path": "scatter of x vs y"},
                db, str(tmp_path),
            )
            assert "error" not in plain
            assert "linked_output" not in plain["matches"][0]

            # With outputs_dir → the figure resolves THROUGH to its output row.
            res = await mh._dispatch_mcp_tool(
                "find_similar_figure",
                {"project_id": pid, "doc": "paper.docx",
                 "description_or_path": "scatter of x vs y",
                 "outputs_dir": outputs},
                db, str(tmp_path),
            )
            assert "error" not in res, res
            linked = res["matches"][0].get("linked_output")
            assert linked is not None
            assert linked["generating_script"] == "plot_scatter.py"
            assert linked["is_archival"] is False
        finally:
            await db.close()
            await doc_store.close_all_doc_stores()

    asyncio.run(_run())
