def test_archival_candidate_filename_heuristic():
    assert oi.archival_candidate("/o/run_old.csv") is True
    assert oi.archival_candidate("/o/run_old_2.csv") is True
    assert oi.archival_candidate("/o/_scratch.json") is True
    assert oi.archival_candidate("/o/run.csv") is False
    assert oi.archival_candidate("/o/older_run.csv") is False  # 'older' != '_old'


def test_identical_content_confirms_archival(tmp_path):
    _write(tmp_path / "a.csv", "x,y\n1,2\n")
    _write(tmp_path / "a_old.csv", "x,y\n1,2\n")
    cls = oi.classify_canonical_archival(
        [str(tmp_path / "a.csv"), str(tmp_path / "a_old.csv")]
    )
    assert cls[str(tmp_path / "a.csv")].is_archival is False
    old = cls[str(tmp_path / "a_old.csv")]
    assert old.is_archival is True
    assert old.canonical_path == str(tmp_path / "a.csv")


def test_different_content_same_pattern_surfaces_both(tmp_path):
    _write(tmp_path / "a.csv", "x,y\n1,2\n")
    _write(tmp_path / "a_old.csv", "x,y,z\n9,9,9\n")  # DIFFERENT content
    cls = oi.classify_canonical_archival(
        [str(tmp_path / "a.csv"), str(tmp_path / "a_old.csv")]
    )
    # Neither collapsed — the _old copy is a genuinely distinct file.
    assert cls[str(tmp_path / "a.csv")].is_archival is False
    assert cls[str(tmp_path / "a_old.csv")].is_archival is False
    assert "DIFFERS" in cls[str(tmp_path / "a_old.csv")].reason


def test_archival_pattern_without_twin_is_not_archival(tmp_path):
    _write(tmp_path / "lonely_old.csv", "x\n1\n")
    cls = oi.classify_canonical_archival([str(tmp_path / "lonely_old.csv")])
    assert cls[str(tmp_path / "lonely_old.csv")].is_archival is False


def test_classification_never_deletes_files(tmp_path):
    _write(tmp_path / "a.csv", "x\n1\n")
    _write(tmp_path / "a_old.csv", "x\n1\n")
    oi.classify_canonical_archival(
        [str(tmp_path / "a.csv"), str(tmp_path / "a_old.csv")]
    )
    # Both files still on disk — classification is purely a label.
    assert (tmp_path / "a.csv").exists()
    assert (tmp_path / "a_old.csv").exists()


