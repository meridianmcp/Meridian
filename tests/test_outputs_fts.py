def _write(path, text: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def _seed_tree(tmp_path):
    """A representative outputs tree with csv/json/npy + _old variants."""
    numpy = pytest.importorskip("numpy")
    # canonical + byte-identical archival copy (SHA confirms archival)
    _write(tmp_path / "results.csv", "temperature,pressure,volume\n300,101,22\n")
    _write(tmp_path / "results_old.csv", "temperature,pressure,volume\n300,101,22\n")
    # same _old name pattern but DIFFERENT content → both distinct, both surfaced
    _write(tmp_path / "metrics.csv", "accuracy,loss\n0.91,0.09\n")
    _write(tmp_path / "metrics_old.csv", "accuracy,loss,f1\n0.80,0.20,0.71\n")
    # json carrying a generating_script fingerprint
    _write(
        tmp_path / "plot.json",
        json.dumps({"generating_script": "plot_results.py",
                    "xdata": [1, 2, 3], "ydata": [4, 5, 6]}),
    )
    # npy — metadata only, never array content
    numpy.save(str(tmp_path / "weights.npy"), numpy.zeros((8, 8), dtype="float32"))
    return tmp_path


