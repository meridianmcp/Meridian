def test_end_to_end_watchdog_rebuild(tmp_path):
    """One real end-to-end pass: a native filesystem create is picked up by the
    watchdog handler, which rebuilds the FTS index so search finds the file."""
    pytest.importorskip("watchdog")
    idx = oi.OutputsIndexer(str(tmp_path))
    idx.start()
    try:
        p = os.path.join(str(tmp_path), "live.csv")
        _write(p, "livecol_marker,v\n1,2\n")
        deadline = time.time() + 10
        found = False
        while time.time() < deadline:
            hits = idx.search("livecol_marker", limit=5)
            if any(h["path"].endswith("live.csv") for h in hits):
                found = True
                break
            time.sleep(0.2)
        assert found, "watchdog-driven rebuild should surface the new file"
    finally:
        idx.stop()


