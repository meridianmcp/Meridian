"""Coverage for the persistent outputs FTS layer + search_outputs (a0e9133e / 5848e8c7).

Exercises the build-on-top of the on-demand glob indexer (06df6ab3 Part 2):

* Persistent DuckDB ``outputs_index`` table + native FTS (Okapi BM25): the table
  is built from a real temp outputs tree (csv/json/npy + other files), and a
  multi-word BM25 query ranks the relevant rows first.
* Per-file cheap fingerprint (5848e8c7): CSV column names, JSON top-level keys,
  and an inferred ``generating_script``.
* Canonical-vs-archival, TWO-STAGE, NEVER destructive: a filename heuristic
  flags candidates; a SHA-256 hash CONFIRMS. Identical content across a
  name-variant pair → the ``_old`` copy is archival (deprioritized, never
  removed); DIFFERENT content despite matching name pattern → both surfaced.
* .npy is metadata-only (no array content indexed); nothing is ever deleted.
* watchdog change triggers a full table + FTS rebuild.
* ``search_outputs`` dispatches through ``_dispatch_mcp_tool`` and is registered
  read-only across the HTTP + stdio surfaces.
"""
