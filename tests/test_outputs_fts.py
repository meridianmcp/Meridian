def test_build_output_rows_covers_every_file_with_kinds(tmp_path):
    _seed_tree(tmp_path)
    rows = {os.path.basename(r.path): r for r in oi.build_output_rows(str(tmp_path))}
    assert set(rows) == {
        "results.csv", "results_old.csv", "metrics.csv", "metrics_old.csv",
        "plot.json", "weights.npy",
    }
    assert rows["results.csv"].kind == "text_content"
    assert rows["weights.npy"].kind == "metadata_only"
    assert rows["results.csv"].sha256 == rows["results_old.csv"].sha256
    assert rows["results_old.csv"].is_archival is True
    assert rows["metrics_old.csv"].is_archival is False
    assert rows["plot.json"].generating_script == "plot_results.py"
    assert rows["results.csv"].csv_columns == ["temperature", "pressure", "volume"]


def test_bm25_multiword_query_ranks_relevant_rows_first(tmp_path):
    _seed_tree(tmp_path)
    idx = oi.OutputsFtsIndex(str(tmp_path))
    try:
        n = idx.rebuild()
        assert n == 6
        hits = idx.search("accuracy loss f1", limit=6)
        assert hits, "expected BM25 matches"
        # The metrics files (which contain accuracy/loss/f1 terms) rank above
        # the temperature/pressure results files.
        top = os.path.basename(hits[0]["path"])
        assert top in {"metrics.csv", "metrics_old.csv"}
        top_paths = {os.path.basename(h["path"]) for h in hits[:2]}
        assert {"metrics.csv", "metrics_old.csv"} <= top_paths
    finally:
        idx.close()


def test_search_deprioritizes_archival_but_keeps_it(tmp_path):
    _seed_tree(tmp_path)
    idx = oi.OutputsFtsIndex(str(tmp_path))
    try:
        idx.rebuild()
        hits = {os.path.basename(h["path"]): h
                for h in idx.search("temperature pressure volume", limit=6)}
        assert "results.csv" in hits and "results_old.csv" in hits
        # archival copy is still returned (never hard-excluded)…
        assert hits["results_old.csv"]["is_archival"] is True
        assert hits["results_old.csv"]["canonical_path"] == str(tmp_path / "results.csv")
        # …but scores strictly below its canonical twin.
        assert hits["results.csv"]["score"] > hits["results_old.csv"]["score"]
    finally:
        idx.close()


