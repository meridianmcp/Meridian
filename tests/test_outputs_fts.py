def test_search_outputs_registered_in_stdio_tool_list():
    """Parse stdio_handler source: search_outputs is advertised there too."""
    import ast
    from pathlib import Path

    src = (
        Path(__file__).resolve().parents[1]
        / "meridian" / "mcp" / "stdio_handler.py"
    ).read_text(encoding="utf-8")
    tree = ast.parse(src)
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "Tool":
            for k in node.keywords:
                if k.arg == "name" and isinstance(k.value, ast.Constant):
                    names.add(k.value.value)
    assert "search_outputs" in names


