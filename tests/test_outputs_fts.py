def test_handle_event_rebuilds_fts_index(tmp_path):
    """A watched-file change routed through handle_event rebuilds the persistent
    table + FTS index so a subsequent search reflects the new file."""
    idx = oi.OutputsIndexer(str(tmp_path))
    _write(tmp_path / "seed.csv", "col_a,col_b\n1,2\n")
    idx.handle_event("created", str(tmp_path / "seed.csv"))
    hits = idx.search("col_a col_b", limit=5)
    assert any(h["path"].endswith("seed.csv") for h in hits)

    # Add a second file, deliver its event → FTS index picks it up (proving the
    # rebuild-on-change, since the FTS index does NOT auto-track source changes).
    _write(tmp_path / "later.csv", "distinct_marker,other\n9,9\n")
    idx.handle_event("created", str(tmp_path / "later.csv"))
    hits2 = idx.search("distinct_marker", limit=5)
    assert any(h["path"].endswith("later.csv") for h in hits2)

    # Delete + event → rebuild drops it from search results.
    os.remove(tmp_path / "later.csv")
    idx.handle_event("deleted", str(tmp_path / "later.csv"))
    hits3 = idx.search("distinct_marker", limit=5)
    assert not any(h["path"].endswith("later.csv") for h in hits3)
    if idx.fts is not None:
        idx.fts.close()


def test_start_stop_builds_initial_fts_index(tmp_path):
    pytest.importorskip("watchdog")
    _write(tmp_path / "pre_existing.csv", "unique_term,x\n1,2\n")
    idx = oi.OutputsIndexer(str(tmp_path))
    idx.start()
    try:
        # start() ran the initial-state rebuild → pre-existing file is indexed.
        hits = idx.search("unique_term", limit=5)
        assert any(h["path"].endswith("pre_existing.csv") for h in hits)
    finally:
        idx.stop()
    assert idx.running is False


def test_end_to_end_watchdog_rebuild(tmp_path):
    """One real end-to-end pass: a native filesystem create is picked up by the
    watchdog handler, which rebuilds the FTS index so search finds the file."""
    pytest.importorskip("watchdog")
    idx = oi.OutputsIndexer(str(tmp_path))
    idx.start()
    try:
        p = os.path.join(str(tmp_path), "live.csv")
        _write(p, "livecol_marker,v\n1,2\n")
        deadline = time.time() + 10
        found = False
        while time.time() < deadline:
            hits = idx.search("livecol_marker", limit=5)
            if any(h["path"].endswith("live.csv") for h in hits):
                found = True
                break
            time.sleep(0.2)
        assert found, "watchdog-driven rebuild should surface the new file"
    finally:
        idx.stop()


