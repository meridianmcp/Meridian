"""Render the L0/L1/L2 tiered handoff markdown file for a Meridian project.

The handoff is the bridge between sessions: a new Claude session reads it
and resumes work with full context. v2.4 tiers the output:

* **L0 (Core, ~500 tokens)** — north star + active pinned decisions. The
  constitution. Always include, even in compressed paste-into-chat mode.
* **L1 (Current state, ~1500 tokens)** — sprint, version goal, last 10
  tasks, active sessions, pending sprint items. What's in flight.
* **L2 (History, ~5000 tokens)** — older task log entries, archived
  sessions, append-only decisions log. Skim if space allows.

An optional ``ai_summary`` field is generated by a tiny Haiku call when
``ANTHROPIC_API_KEY`` is set. Falls back to the first task description so
the field is always populated.
"""

