# b7f41c73 — Postgres returns real ``datetime`` objects for timestamp columns
# (completed_at, added_at, claimed_at, created_at, last_seen) while SQLite returns
# ISO strings. Any delta-path code that ``.strip()``s or ``json.dumps``es those
# fields crashed on prod ("Object of type datetime is not JSON serializable" /
# AttributeError on .strip). These helpers make both paths datetime-safe.
def _iso_ts(value: Any) -> str | None:
    """Coerce a timestamp (``datetime`` OR str OR None) to an ISO-ish string.

    ``datetime`` objects (Postgres) are rendered via ``isoformat``; strings
    (SQLite) pass through unchanged; anything else stringifies. ``None`` /empty
    return ``None`` so callers can distinguish "no timestamp" from a value.
    """
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, str):
        return value or None
    return str(value)


# Timestamp fields on sprint-item / task / session dicts that Postgres returns as
# real ``datetime`` objects — coerced to strings before any JSON serialization so
# a delta handoff never trips ``json.dumps`` on a naive datetime.
_TS_FIELDS = (
    "completed_at",
    "added_at",
    "claimed_at",
    "created_at",
    "updated_at",
    "started_at",
    "last_seen",
)


def _json_default(obj: Any) -> str:
    """``json.dumps(default=...)`` hook: serialize ``datetime`` (and any other
    non-JSON object) as its string form so a Postgres timestamp never raises
    "Object of type datetime is not JSON serializable" (b7f41c73)."""
    if isinstance(obj, datetime):
        return obj.isoformat()
    return str(obj)


def _ts_safe_items(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Return shallow copies of ``items`` with every known timestamp field coerced
    to an ISO string (b7f41c73). Non-dict entries pass through untouched. This is
    the single choke-point that makes the delta path datetime-safe before render
    and any downstream serialization."""
    out: list[dict[str, Any]] = []
    for item in items:
        if not isinstance(item, dict):
            out.append(item)
            continue
        copy = dict(item)
        for field in _TS_FIELDS:
            if field in copy and isinstance(copy[field], datetime):
                copy[field] = _iso_ts(copy[field])
        out.append(copy)
    return out


def _parse_ts(value: Any) -> datetime | None:
    """Parse a timestamp (``datetime`` OR ISO-ish str) into a naive ``datetime``.

    Accepts the same shapes as :func:`_iso_ts` — Postgres ``datetime`` objects and
    SQLite strings — and normalizes away the ``T`` separator, a trailing ``Z``, a
    ``+HH:MM`` offset, and optional fractional seconds. Returns ``None`` on empty
    or unparseable input so callers can skip bad rows instead of crashing (302db181).
    """
    if value is None:
        return None
    if isinstance(value, datetime):
        # Drop tz so mixed aware/naive rows compare without raising.
        return value.replace(tzinfo=None)
    text = str(value).strip()
    if not text:
        return None
    normalized = text.replace("T", " ")
    if normalized.endswith("Z"):
        normalized = normalized[:-1]
    if "+" in normalized:
        normalized = normalized.split("+", 1)[0].strip()
    # A bare "-" offset (…:00-05:00) — split on the offset colon-group, keeping the
    # date's own hyphens. Only trim a trailing "-HH:MM" style suffix.
    for fmt in ("%Y-%m-%d %H:%M:%S.%f", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y-%m-%d"):
        try:
            return datetime.strptime(normalized, fmt)
        except ValueError:
            continue
    return None


def compute_session_span(timestamps: list[Any]) -> dict[str, Any]:
    """Summarize a span of activity from a list of timestamps (302db181).

    ``timestamps`` may mix ``datetime`` objects (Postgres) and ISO strings
    (SQLite); ``None``/empty/unparseable entries are skipped. Returns a dict:

    * ``first`` / ``last`` — ISO strings of the earliest / latest activity (or None)
    * ``distinct_days`` — count of distinct calendar days touched
    * ``elapsed_seconds`` — total wall-clock span first→last, in seconds
    * ``elapsed_human`` — a compact "2d 3h"/"45m"/"30s" rendering of that span
    * ``count`` — number of usable timestamps

    A pure function — no I/O — so it is trivially unit-testable and safe to call
    from any handoff path. An empty / all-unparseable input yields a zeroed span
    rather than raising.
    """
    parsed = [dt for dt in (_parse_ts(t) for t in (timestamps or [])) if dt is not None]
    if not parsed:
        return {
            "first": None,
            "last": None,
            "distinct_days": 0,
            "elapsed_seconds": 0,
            "elapsed_human": "0s",
            "count": 0,
        }
    first = min(parsed)
    last = max(parsed)
    distinct_days = len({dt.date() for dt in parsed})
    elapsed = int((last - first).total_seconds())
    return {
        "first": first.isoformat(),
        "last": last.isoformat(),
        "distinct_days": distinct_days,
        "elapsed_seconds": elapsed,
        "elapsed_human": _humanize_span(elapsed),
        "count": len(parsed),
    }


def _humanize_span(seconds: int) -> str:
    """Render an elapsed second-count as a compact "2d 3h" / "45m" / "30s" string
    (302db181). Shows the two most-significant non-zero units; 0 → "0s"."""
    seconds = max(0, int(seconds))
    if seconds == 0:
        return "0s"
    days, rem = divmod(seconds, 86400)
    hours, rem = divmod(rem, 3600)
    minutes, secs = divmod(rem, 60)
    parts = [
        (days, "d"),
        (hours, "h"),
        (minutes, "m"),
        (secs, "s"),
    ]
    nonzero = [f"{val}{unit}" for val, unit in parts if val]
    return " ".join(nonzero[:2])


def _render_session_span_block(span: dict[str, Any]) -> str:
    """Render the computed :func:`compute_session_span` dict as a one-block markdown
    footer for the handoff (302db181). Returns "" when there is no activity so an
    empty-state handoff carries no misleading span line."""
    if not span or not span.get("count"):
        return ""
    first = (span.get("first") or "").replace("T", " ")[:19]
    last = (span.get("last") or "").replace("T", " ")[:19]
    days = span.get("distinct_days", 0)
    day_word = "day" if days == 1 else "days"
    return (
        "## Session span\n"
        f"- First activity: {first}\n"
        f"- Last activity: {last}\n"
        f"- Elapsed: {span.get('elapsed_human', '0s')} "
        f"across {days} calendar {day_word}"
    )


def _completed_after(
    completed_at: Any,
    since_ts: Any,
) -> bool:
    # b7f41c73 — accept datetime OR str for BOTH operands. On Postgres these
    # arrive as datetime objects; the old str-only ``.strip()`` path raised
    # AttributeError. Coerce to ISO strings first, then compare.
    completed_at = _iso_ts(completed_at)
    since_ts = _iso_ts(since_ts)
    if not completed_at:
        return False
    if not since_ts:
        return True
    def _parse(ts: str) -> datetime:
        normalized = ts.strip().replace("T", " ")
        if normalized.endswith("Z"):
            normalized = normalized[:-1]
        if "+" in normalized:
            normalized = normalized.split("+", 1)[0].strip()
        if "." in normalized:
            return datetime.strptime(normalized, "%Y-%m-%d %H:%M:%S.%f")
        return datetime.strptime(normalized, "%Y-%m-%d %H:%M:%S")

    return _parse(completed_at) >= _parse(since_ts)


def _collect_diagnostic_tasks(
    tasks: list[dict[str, Any]],
    limit: int = 3,
) -> list[dict[str, Any]]:
    """77a29c8b — Return up to ``limit`` recent task-log entries whose ``kind``
    is 'blocked' or 'found', newest first.

    These entries carry diagnostic signal (gate failures, discovered gotchas,
    test failures, etc.) that must be visible even in compact/delta/starter
    paths to prevent executors from repeating work already known to fail.
    The list is intentionally small and bounded so it does not defeat the
    size-reduction purpose of those paths.
    """
    _DIAGNOSTIC_KINDS = {"blocked", "found"}
    return [
        t for t in tasks if (t.get("kind") or "") in _DIAGNOSTIC_KINDS
    ][:limit]


def _render_delta_handoff(
    project: dict[str, Any],
    *,
    generated_at: str,
    completed_items: list[dict[str, Any]],
    in_progress_items: list[dict[str, Any]],
    pending_sprint_items: list[dict[str, Any]],
    quick_start_goal: str,
    identity: str | None = None,
    diagnostic_tasks: list[dict[str, Any]] | None = None,
) -> str:
    """Return a compact handoff for back-to-back goal runs in one session.

    ``identity`` (bdc251ec), when known, pre-fills the start_session ``human_id``.
    ``diagnostic_tasks`` (77a29c8b), when non-empty, surfaces recent blocked/found
    entries so repeated gate failures are not silently dropped from delta mode.
    """
    # bc834237 — cap the pending list so a large backlog never bloats the delta
    # payload. Delta is richer than starter (session-continuity context), so the
    # cap is 20 items (vs starter's 3) with titles truncated to 150 chars
    # (vs starter's 80 but consistent with the 200-char diagnostic precedent).
    # Selection is priority-ranked (urgent > high > normal > low), NOT raw
    # incoming order: _prepare_pending_sprint_items only sorts by dependency
    # topology, which has no relationship to priority, so a genuinely urgent
    # item could otherwise land past position 20 purely by chance and be
    # silently hidden. A stable sort preserves the caller's relative ordering
    # within each priority tier.
    _DELTA_PENDING_CAP = 20
    # 7732e096 — completed_items had ZERO cap, unlike pending (bc834237): a
    # session's first delta call on a project with a long completed-item
    # history (even after the since_ts scoping fix above) could still iterate
    # every historical done/skipped/failed/pushed item with full untruncated
    # titles. Mirror the exact same cap/truncation pattern used for pending
    # (same 20-item cap, same 150-char title truncation, same "+N more"
    # summary line) so this section is bounded the same way.
    _DELTA_COMPLETED_CAP = 20
    _DELTA_TITLE_MAX = 150
    # 04f03ee4 — one-liner start instruction at very top of delta output
    lines = [
        f"To start fresh: start_session(project_name=\"{project['name']}\", session_name=\"describe-what-youre-doing\"{_human_id_clause(identity)})  # project_id={project['id']}",
        "",
        f"# Session Update — {project['name']}",
        f"_Generated at {generated_at} (delta mode)_",
        "",
    ]
    # "Currently running:" — claimed in_progress items shown first so the
    # planning chat immediately knows what's active without scrolling.
    if in_progress_items:
        lines.append("Currently running:")
        for item in in_progress_items:
            claimed = item.get("claimed_by") or ""
            suffix = f" (claimed by {claimed})" if claimed else ""
            lines.append(f"- {item['id']} — {item['title']}{suffix}")
        lines.append("")
    lines.append("Completed since last handoff:")
    if completed_items:
        shown_completed = completed_items[:_DELTA_COMPLETED_CAP]
        hidden_completed = completed_items[_DELTA_COMPLETED_CAP:]
        for item in shown_completed:
            short_title = (item.get("title") or "").strip()[:_DELTA_TITLE_MAX]
            lines.append(f"- {item['id']} — {short_title}")
        if hidden_completed:
            lines.append(f"  +{len(hidden_completed)} more completed")
    else:
        lines.append("- none")
    _PRIORITY_RANK = {"urgent": 0, "high": 1, "normal": 2, "low": 3}
    lines += ["", "Pending:"]
    if pending_sprint_items:
        ranked = sorted(
            pending_sprint_items,
            key=lambda it: _PRIORITY_RANK.get(
                (it.get("priority") or "normal").strip().lower(), 2
            ),
        )
        shown = ranked[:_DELTA_PENDING_CAP]
        hidden = ranked[_DELTA_PENDING_CAP:]
        for item in shown:
            suffix = ""
            if item.get("possibly_done"):
                suffix = " ⚠ possibly done — verify before executing"
            short_title = item["title"].strip()[:_DELTA_TITLE_MAX]
            lines.append(
                f"- {item['id']} [{item['status']}] {short_title}{suffix}"
            )
        if hidden:
            urgent_count = sum(
                1 for it in hidden
                if (it.get("priority") or "normal").strip().lower() == "urgent"
            )
            high_count = sum(
                1 for it in hidden
                if (it.get("priority") or "normal").strip().lower() == "high"
            )
            note_parts = []
            if urgent_count:
                note_parts.append(f"{urgent_count} urgent")
            if high_count:
                note_parts.append(f"{high_count} high-priority")
            note = f" ({', '.join(note_parts)})" if note_parts else ""
            lines.append(f"  +{len(hidden)} more pending{note}")
    else:
        lines.append("- none")
    # 77a29c8b — surface recent diagnostic entries (blocked/found) so a resumed
    # session sees known failures and gotchas even in the compact delta path.
    if diagnostic_tasks:
        lines += ["", "Recent diagnostics (blocked/found):"]
        for t in diagnostic_tasks:
            kind = (t.get("kind") or "").upper()
            desc = (t.get("description") or "").strip()[:200]
            lines.append(f"- [{kind}] {desc}")
    lines += ["", "Next:", quick_start_goal]
    return "\n".join(lines) + "\n"


async def _generate_ai_summary(
    recent_tasks: list[dict[str, Any]],
    sprint: str | None,
    summarizer: Callable[[str], Any] | None = None,
) -> str:
    """Produce a 2-3 sentence "what was done, what's next" blurb.

    Tries a Haiku call when ``ANTHROPIC_API_KEY`` is set; otherwise falls
    back to the first task description so the field is always populated.
    Pass ``summarizer`` to inject a stub in tests.
    """
    fallback = ""
    if recent_tasks:
        first = recent_tasks[0]
        desc = (first.get("description") or "").strip()
        if desc:
            fallback = desc[:200].rstrip() + ("…" if len(desc) > 200 else "")
    if not fallback:
        fallback = "No recent activity logged."

    # Build a short prompt — capped to avoid wasting tokens on a tiny call.
    task_lines = []
    for t in recent_tasks[:8]:
        status = (t.get("status") or "?").upper()
        d = (t.get("description") or "").strip().replace("\n", " ")
        if len(d) > 160:
            d = d[:160].rstrip() + "…"
        task_lines.append(f"- [{status}] {d}")
    sprint_line = f"Sprint: {sprint.strip()}" if sprint else ""
    prompt = (
        "In 2-3 sentences (no preamble), summarize what's been done recently "
        "and the best next action. Be specific. Avoid filler.\n\n"
        f"{sprint_line}\n\n" + "\n".join(task_lines)
    )

    if summarizer is not None:
        try:
            result = summarizer(prompt)
            if hasattr(result, "__await__"):
                result = await result  # type: ignore[misc]
            if isinstance(result, dict):
                text = result.get("text") or result.get("summary") or ""
            else:
                text = str(result)
            text = text.strip()
            if text:
                return text
        except Exception:  # noqa: BLE001 — never break handoff on summary fail
            pass

    api_key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not api_key:
        return fallback
    try:
        import anthropic  # type: ignore[import]

        def _sync_call() -> str:
            client = anthropic.Anthropic(api_key=api_key)
            resp = client.messages.create(
                model="claude-haiku-4-5",
                max_tokens=200,
                messages=[{"role": "user", "content": prompt}],
            )
            return "".join(
                getattr(block, "text", "") for block in resp.content
            ).strip()

        loop = asyncio.get_event_loop()
        text = await asyncio.wait_for(
            loop.run_in_executor(None, _sync_call),
            timeout=30.0,
        )
        return text or fallback
    except (asyncio.TimeoutError, Exception):  # noqa: BLE001
        return fallback


async def synthesize_search_answer(
    query: str,
    results: dict[str, Any],
    *,
    summarizer: Callable[[str], Any] | None = None,
) -> dict[str, Any]:
    """ebc242ad — turn raw search hits into a short, CITED answer, not just a list.

    Reuses the exact Haiku-tier pattern as :func:`_generate_ai_summary`: a cheap
    Haiku call when ``ANTHROPIC_API_KEY`` is set (or an injected ``summarizer`` in
    tests), with a DETERMINISTIC fallback — on no key / failure it returns
    ``synthesized: False`` and the caller shows the raw results list. Not new infra;
    the summary pattern applied to search.

    ``results`` is :func:`meridian.db.search_all`'s grouped output. Returns
    ``{answer, cited, synthesized}``: ``answer`` is a 2-3 sentence response that
    cites its sources inline as ``[n]``; ``cited`` maps those numbers to
    ``{n, kind, id, title}``; ``synthesized`` is False when it fell back.
    """
    sources: list[dict[str, Any]] = []
    for kind in ("sprint_items", "notes", "decisions", "tasks"):
        for r in (results.get(kind) or []):
            title = (r.get("title") or r.get("description") or "").strip().replace("\n", " ")
            sources.append({"kind": kind, "id": r.get("id"), "title": title[:160]})

    out: dict[str, Any] = {"answer": "", "cited": [], "synthesized": False}
    if not sources:
        return out

    numbered = "\n".join(
        f"[{i + 1}] ({s['kind']}) {s['title']}" for i, s in enumerate(sources[:12])
    )
    prompt = (
        "Answer the question in 2-3 sentences using ONLY the search results below. "
        "Cite the results you use inline as [n]. If they do not answer it, say so "
        "plainly. No preamble.\n\n"
        f"Question: {query}\n\nResults:\n{numbered}"
    )

    text = ""
    if summarizer is not None:
        try:
            res = summarizer(prompt)
            if hasattr(res, "__await__"):
                res = await res  # type: ignore[misc]
            text = ((res.get("text") or res.get("summary") or "") if isinstance(res, dict)
                    else str(res)).strip()
        except Exception:  # noqa: BLE001 — never break search on a synthesis failure
            text = ""

    if not text:
        api_key = os.environ.get("ANTHROPIC_API_KEY", "")
        if api_key:
            try:
                import anthropic  # type: ignore[import]

                def _sync_call() -> str:
                    client = anthropic.Anthropic(api_key=api_key)
                    resp = client.messages.create(
                        model="claude-haiku-4-5",
                        max_tokens=250,
                        messages=[{"role": "user", "content": prompt}],
                    )
                    return "".join(getattr(b, "text", "") for b in resp.content).strip()

                loop = asyncio.get_event_loop()
                text = await asyncio.wait_for(
                    loop.run_in_executor(None, _sync_call), timeout=30.0
                )
            except (asyncio.TimeoutError, Exception):  # noqa: BLE001
                text = ""

    if not text:
        return out  # deterministic fallback: no answer, caller shows raw results

    cited_nums = {int(m) for m in re.findall(r"\[(\d+)\]", text)}
    cited = [
        {"n": i + 1, **sources[i]}
        for i in range(min(len(sources), 12))
        if (i + 1) in cited_nums
    ]
    # If the model cited nothing parseable, attribute the top few as provenance.
    if not cited:
        cited = [{"n": i + 1, **s} for i, s in enumerate(sources[:3])]
    return {"answer": text, "cited": cited, "synthesized": True}


