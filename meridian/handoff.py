# 490e100d — workspace-level default MCP tool priority per semantic task
# category. Generalizes 4d1fb28f's per-item required_tool pin up one level:
# a workspace admin sets a durable default (e.g. {"code-reading": "Serena:
# find_symbol"}) via update_workspace_settings(tool_priority_map=...) ONCE,
# instead of a planner pinning required_tool on every matching item. Same
# structural-enforcement fix class as 22b7f3f1 found missing for advisory-only
# tool preference: rendered UNCONDITIONALLY (hard directive), not a hint that
# can lose to attention decay. An item-level required_tool pin always wins —
# this is only consulted for items that do NOT already carry one.
# ---------------------------------------------------------------------------

_BUILTIN_TASK_CATEGORY_KEYWORDS: dict[str, frozenset[str]] = {
    "code-reading": frozenset({
        "read", "understand", "review", "explore", "inspect", "investigate",
        "audit", "trace", "locate", "look at", "analyze", "analyse",
        "familiarize",
    }),
    "code-writing": frozenset({
        "implement", "write", "add", "refactor", "build", "create",
        "rewrite", "patch", "generate",
    }),
    "bug-fixing": frozenset({"fix", "bug", "regression", "broken", "crash"}),
    "research": frozenset({
        "research", "search for", "look up", "docs", "documentation",
        "paper", "investigate",
    }),
    "testing": frozenset({"test", "verify", "validate", "coverage", "regression"}),
    "planning": frozenset({"plan", "design", "spec", "scope", "architecture"}),
}


def _task_category_keywords(category: str) -> frozenset[str]:
    """Return the keyword set used to match a sprint item against ``category``.

    Known categories (``_BUILTIN_TASK_CATEGORY_KEYWORDS``) use a curated
    keyword set; unknown/custom categories fall back to the significant
    words in the category name itself (kebab/snake/space-split, 3+ chars),
    so a workspace admin can define a category the classifier has never seen
    (e.g. ``"database-work"``) and still get a reasonable match without a
    code change."""
    known = _BUILTIN_TASK_CATEGORY_KEYWORDS.get(category.strip().lower())
    if known:
        return known
    words = re.findall(r"[a-z0-9]+", category.lower())
    return frozenset(w for w in words if len(w) >= 3)


def _classify_sprint_item_task_category(
    item: dict[str, Any], categories: list[str]
) -> str | None:
    """Return the first ``categories`` entry whose keywords appear in the
    item's title/notes, or None if none match. ``categories`` order is the
    caller's priority order (a workspace admin's dict insertion order)."""
    text = f"{item.get('title') or ''} {item.get('notes') or ''}".lower()
    for category in categories:
        if any(kw in text for kw in _task_category_keywords(category)):
            return category
    return None


def _build_workspace_tool_priority_clause(
    items: list[dict[str, Any]],
    tool_priority_map: dict[str, str] | None,
) -> str:
    """490e100d — build a ``<workspace_tool_priority>`` XML clause for the
    /goal block from the workspace-level ``tool_priority_map`` default.

    Mirrors ``_build_required_tool_clause``'s hard-guidance rendering
    (unconditional, no opt-in flag — unlike the soft model-tier hint) but the
    pin source is a workspace/project default keyed by semantic task category
    instead of a per-item field. An item that already carries its own
    ``required_tool`` pin is skipped here — the item-level pin always wins,
    consistent with 4d1fb28f being the more specific override. Returns an
    empty string when ``tool_priority_map`` is unset/empty or no pending item
    matches any configured category.
    """
    if not tool_priority_map:
        return ""
    categories = list(tool_priority_map.keys())
    pins: list[str] = []
    for it in items:
        iid = it.get("id")
        if not iid or it.get("required_tool"):
            continue
        category = _classify_sprint_item_task_category(it, categories)
        if category is None:
            continue
        tool = tool_priority_map.get(category)
        if not tool:
            continue
        pins.append(f"{iid} ({category}): {tool}")
    if not pins:
        return ""
    body = (
        "The following sprint items match a workspace default tool-priority "
        "category — this is a hard requirement, not a suggestion: "
        + "; ".join(pins)
    )
    return f"\n<workspace_tool_priority>{_xml_escape(body)}</workspace_tool_priority>"


def build_item_briefing(
    item: dict[str, Any],
    *,
    test_floor: int = _DEFAULT_GOAL_TEST_FLOOR,
    max_turns: int = _DEFAULT_GOAL_MAX_TURNS,
    hitl_auto_answer_mode: int = 0,
) -> str:
    """Generate a deterministic, XML-tagged briefing for a SINGLE sprint item.

    Mirrors ``_build_quick_start_goal``'s structural approach — same XML-tag
    vocabulary (role / first_step / task / resources / completion_criteria /
    stop_conditions) but scoped to one item row instead of a batch.  Intended
    to replace the ad-hoc, hand-written per-item briefings that were previously
    pasted into planning chat.

    Parameters
    ----------
    item:
        A sprint_item row dict (as returned by ``db.get_sprint_item``).
    test_floor:
        Minimum passing test count required for completion (default 2150).
    max_turns:
        Maximum turns ceiling — same semantics as ``_build_quick_start_goal``.
    hitl_auto_answer_mode:
        0 = stop if HITL triggered; 1/2 = skip blocked items (auto-answer on).

    Returns a ``/goal``-prefixed XML string ready to paste as a session goal.
    """
    try:
        _turns = int(max_turns)
        if _turns <= 0:
            _turns = _DEFAULT_GOAL_MAX_TURNS
        else:
            _turns = min(500, _turns)
    except (TypeError, ValueError):
        _turns = _DEFAULT_GOAL_MAX_TURNS

    _hitl_clause = (
        "Do NOT file HITLs — auto-answer is on, skip blocked items and continue."
        if int(hitl_auto_answer_mode or 0) >= 1
        else "or if HITL triggered."
    )

    iid = (item.get("id") or "").strip()
    title = (item.get("title") or "").strip()
    item_group = (item.get("item_group") or "").strip()
    notes = (item.get("notes") or "").strip()
    wave = (item.get("wave") or "").strip()
    priority = (item.get("priority") or "normal").strip()
    depends_on = (item.get("depends_on") or "").strip()
    blocker_kind = (item.get("blocker_kind") or "").strip()
    milestone_type = (item.get("milestone_type") or "task").strip()
    required_tool = (item.get("required_tool") or "").strip()

    # Render the touches_resources field as a readable list of paths/identifiers.
    raw_resources = item.get("touches_resources")
    resources_lines: list[str] = []
    if raw_resources:
        import json as _json  # noqa: PLC0415 — used only here
        ids: list[Any] = []
        if isinstance(raw_resources, str) and raw_resources.strip():
            try:
                parsed = _json.loads(raw_resources)
                ids = parsed if isinstance(parsed, list) else [raw_resources]
            except Exception:  # noqa: BLE001
                ids = [raw_resources]
        elif isinstance(raw_resources, list):
            ids = raw_resources
        for ident in ids:
            s = str(ident).strip()
            if not s:
                continue
            if s.startswith("inferred:"):
                s = s[len("inferred:"):]
            head, sep, tail = s.partition(":")
            resources_lines.append(tail.strip() if sep and head.isalpha() else s)

    # --- Build each XML section ---

    # <executor_directive> — same directive as the autonomous executor /goal.
    role_text = (
        "You are an executor. Claim and execute the following sprint item "
        "immediately without asking for direction or confirmation."
    )

    # <first_step> — always start by reloading the live board.
    first_step_text = (
        'First call get_sprint_items(status="pending") to confirm this item is '
        "still pending and unclaimed, then claim it with claim_sprint_item()."
    )

    # <task> — core item description.
    task_parts: list[str] = []
    if iid:
        task_parts.append(f"Item: {iid}")
    if title:
        task_parts.append(f"Title: {title}")
    if item_group:
        task_parts.append(f"Group: {item_group}")
    if wave:
        task_parts.append(f"Wave: {wave}")
    if priority and priority != "normal":
        task_parts.append(f"Priority: {priority}")
    if milestone_type and milestone_type != "task":
        task_parts.append(f"Milestone type: {milestone_type}")
    if depends_on:
        task_parts.append(f"Depends on: {depends_on}")
    if blocker_kind:
        task_parts.append(f"Blocker kind: {blocker_kind}")
    if notes:
        task_parts.append(f"Notes: {notes}")
    task_text = "; ".join(task_parts) if task_parts else "(no item details)"

    # <resources> — files/symbols declared on the item.
    resources_text = ", ".join(resources_lines) if resources_lines else ""

    # <completion_criteria> — item marked done + targeted tests pass.
    # 0d5453bc — per-item verification uses targeted tests only; the full
    # suite (pixi run test {test_floor}+) runs once at the end of the whole
    # megasprint, not after each individual item. For timing/comparative
    # questions prefer CI history over repeated local runs.
    completion_text = (
        f"Done when complete_sprint_item({iid!r}) is called, "
        f"targeted tests for this item pass (run pixi run test passes {test_floor}+ "
        "only ONCE at the very end of the whole megasprint -- not after each item; "
        "per-item verification: run only the specific tests relevant to this change), "
        "and generate_handoff() is called at the end."
    )

    # <not_done_until> — single-item equivalent.
    not_done_text = (
        "complete_sprint_item() has been called for this item. "
        "Do not stop or hand off while the item is still pending."
    )

    # <stop_conditions>
    stop_text = f"Stop after {_turns} turns {_xml_escape(_hitl_clause)}"

    parts = [
        "/goal",
        f"<executor_directive>{_xml_escape(role_text)}</executor_directive>",
        f"<first_step>{_xml_escape(first_step_text)}</first_step>",
        f"<task>{_xml_escape(task_text)}</task>",
    ]
    if resources_text:
        parts.append(f"<resources>{_xml_escape(resources_text)}</resources>")
    # 4d1fb28f — item-level tool/plugin pin: rendered as a dedicated, hard
    # directive tag (not folded into <task> prose) so it reaches the executor
    # as guidance it cannot skim past, mirroring the batch /goal's
    # <required_tool> clause (_build_required_tool_clause).
    if required_tool:
        parts.append(
            "<required_tool>"
            + _xml_escape(
                f"This item MUST use the following tool/plugin — this is a "
                f"hard requirement, not a suggestion: {required_tool}"
            )
            + "</required_tool>"
        )
    parts += [
        f"<completion_criteria>{_xml_escape(completion_text)}</completion_criteria>",
        f"<not_done_until>{_xml_escape(not_done_text)}</not_done_until>",
        f"<stop_conditions>{stop_text}</stop_conditions>",
    ]
    return "\n".join(parts)


def _extract_keywords(
    text: str, extra_stop: "frozenset[str] | set[str] | None" = None
) -> set[str]:
    """Extract significant lowercase keywords from a title/description string.

    ``extra_stop`` (23e79944) is an optional second stop set removed on top of
    the base one. The possibly-done heuristic passes :data:`_MERIDIAN_STOP_WORDS`
    so Meridian-domain high-frequency terms (session/handoff/notes/decisions/…)
    don't count as keyword overlap — they appear in nearly every task-log entry
    and otherwise produced constant false ``possibly_done`` flags. Other callers
    (code-pointer / touches-files matching) pass nothing and keep those terms.
    """
    stop = {
        "a", "an", "the", "and", "or", "in", "on", "at", "to", "for",
        "of", "is", "it", "fix", "add", "update", "remove", "change",
        "with", "from", "by", "via", "use", "set", "get", "put", "new",
        "this", "that", "into", "as", "be", "has", "was", "not", "no",
    }
    words = re.findall(r"[a-z0-9_/-]{3,}", text.lower())
    kws = {w for w in words if w not in stop}
    if extra_stop:
        kws -= set(extra_stop)
    return kws


# 23e79944 — Meridian-domain high-frequency terms. These show up in almost every
# task-log entry and commit message ("complete sprint item", "generate handoff",
# "pin decision", …), so counting them as keyword overlap made _annotate_possibly_done
# flag nearly every pending item. Filtered out (on top of the base stop set) only
# in the possibly-done heuristic — code-pointer/file matching still see them since
# they're legitimate symbol names there.
_MERIDIAN_STOP_WORDS: "frozenset[str]" = frozenset({
    "session", "sessions", "handoff", "handoffs", "note", "notes",
    "decision", "decisions", "sprint", "item", "items", "task", "tasks",
    "project", "projects", "meridian", "test", "tests", "passing", "pass",
    "dashboard", "tool", "tools", "mcp", "feat", "docs", "complete",
    "completed", "log", "logs", "board", "context", "field",
})


def reconcile_sprint_items(
    pending_items: list[dict[str, Any]],
    commits: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Cross-reference pending sprint items against commit messages.

    Each commit should be a dict with 'sha' and 'message' keys.
    confidence='high' if 3+ keywords overlap, 'medium' if 1-2 keywords overlap.
    Returns only items that have at least one keyword match.
    """
    results = []
    for item in pending_items:
        title = item.get("title") or ""
        kws = _extract_keywords(title)
        if len(kws) < 2:
            continue
        matching_commits: list[dict[str, str]] = []
        max_overlap = 0
        for commit in commits:
            msg = commit.get("message") or ""
            msg_kws = _extract_keywords(msg)
            overlap = len(kws & msg_kws)
            if overlap >= 1:
                matching_commits.append({
                    "sha": (commit.get("sha") or "")[:12],
                    "message": msg[:120],
                })
                max_overlap = max(max_overlap, overlap)
        if matching_commits:
            confidence = "high" if max_overlap >= 3 else "medium"
            results.append({
                "item_id": item["id"],
                "title": title[:200],
                "matching_commits": matching_commits[:5],
                "confidence": confidence,
            })
    return results


@functools.lru_cache(maxsize=1)
def _migration_blocks() -> tuple[tuple[str, frozenset[str]], ...]:
    """Parse db/migrations.py into ``(migration_name, keyword_set)`` blocks.

    7e212375 — each block's keyword set is the words in its ``_migrate_*`` name
    plus the quoted table/column identifiers it touches, so the drift check can
    point at the specific ``_migrate_X`` that already added a thing. Cached: the
    file is static at runtime. Returns ``()`` if the file can't be read.
    """
    try:
        src = (
            Path(__file__).resolve().parent / "db" / "migrations.py"
        ).read_text(encoding="utf-8")
    except Exception:  # noqa: BLE001
        return ()
    parts = re.split(r"\nasync def (_migrate_[a-z0-9_]+)\(", src)
    blocks: list[tuple[str, frozenset[str]]] = []

    def _add(toks: set[str], ident: str) -> None:
        ident = ident.lower()
        if len(ident) >= 3:
            toks.add(ident)
        toks.update(p for p in ident.split("_") if len(p) >= 3)

    _col_types = (
        r"TEXT|INTEGER|REAL|BLOB|BOOLEAN|BOOL|TIMESTAMPTZ|TIMESTAMP|"
        r"BIGINT|BIGSERIAL|SERIAL|JSONB|JSON|NUMERIC|DATE"
    )
    # parts = [preamble, name1, body1, name2, body2, ...]
    for i in range(1, len(parts), 2):
        name = parts[i]
        body = parts[i + 1] if i + 1 < len(parts) else ""
        toks: set[str] = set()
        for p in name.replace("_migrate_", "").split("_"):
            if len(p) >= 3:
                toks.add(p)
        # Table / index names.
        for tbl in re.findall(
            r"(?:CREATE TABLE(?: IF NOT EXISTS)?|ALTER TABLE|\bON)\s+"
            r"([a-z][a-z0-9_]+)",
            body, re.I,
        ):
            _add(toks, tbl)
        # Columns added via the helper: add_column_if_missing(db, "tbl", "col", ...).
        for tbl, col in re.findall(
            r'add_column_if_missing\(\s*\w+,\s*"([^"]+)",\s*"([^"]+)"', body
        ):
            _add(toks, tbl)
            _add(toks, col)
        # Columns / ADD COLUMN declarations followed by a SQL type.
        for col in re.findall(
            rf"(?:\n\s+|ADD COLUMN(?: IF NOT EXISTS)?\s+)([a-z][a-z0-9_]+)\s+"
            rf"(?:{_col_types})",
            body, re.I,
        ):
            _add(toks, col)
        blocks.append((name, frozenset(toks)))
    return tuple(blocks)


def detect_sprint_item_drift(
    title: str,
    recent_commits: list[Any] | None = None,
    *,
    migration_blocks: "tuple[tuple[str, frozenset[str]], ...] | None" = None,
    min_overlap: int = 3,
) -> list[dict[str, Any]]:
    """Spot a sprint-item title that may already be implemented.

    7e212375 — compares the title's keywords against (1) each migration block's
    keyword set and (2) recent commit messages. A match needs ``min_overlap``
    (default 3) shared keywords. Returns ``[{kind, ref, detail}]`` — ``kind`` is
    'migration' (ref=_migrate_X) or 'commit' (ref=sha) — empty when nothing
    crosses the threshold. ``migration_blocks`` is injectable for tests; it
    defaults to :func:`_migration_blocks`.
    """
    kws = _extract_keywords(title)
    matches: list[dict[str, Any]] = []
    if len(kws) < min_overlap:
        return matches
    blocks = migration_blocks if migration_blocks is not None else _migration_blocks()
    for name, toks in blocks:
        overlap = kws & set(toks)
        if len(overlap) >= min_overlap:
            matches.append({
                "kind": "migration",
                "ref": name,
                "detail": f"shares {sorted(overlap)} with migrations.py/{name}",
            })
            break  # one schema match is enough signal
    for c in (recent_commits or []):
        if isinstance(c, str):
            msg, sha = c, ""
        else:
            msg, sha = (c.get("message") or ""), str(c.get("sha") or "")
        overlap = kws & _extract_keywords(msg)
        if len(overlap) >= min_overlap:
            matches.append({
                "kind": "commit",
                "ref": sha[:12] or msg[:40],
                "detail": msg[:120],
            })
    return matches


def extract_transcript_narrative(
    transcript_path: str,
    *,
    max_messages: int = 40,
    max_chars: int = 4000,
) -> str:
    """Read a Claude Code transcript.jsonl and return a compact work narrative.

    571b8b60 — pulls the assistant's text turns (what it said it did), NOT
    verbatim tool inputs/outputs, so the Stop hook can build a richer delta
    handoff than task-log lines alone. Bounded: keeps the last ``max_messages``
    assistant text turns, capped to ``max_chars`` (most-recent kept). Returns
    "" on any error, a missing file, or an empty/text-less transcript — callers
    treat that as "no narrative" and fall back to the plain delta.
    """
    try:
        p = Path(transcript_path)
        if not p.is_file():
            return ""
        raw = p.read_text(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        return ""
    texts: list[str] = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except Exception:  # noqa: BLE001 — skip non-JSON lines
            continue
        msg = obj.get("message") if isinstance(obj, dict) else None
        if not isinstance(msg, dict) or msg.get("role") != "assistant":
            continue
        content = msg.get("content")
        if isinstance(content, str):
            t = content.strip()
            if t:
                texts.append(t)
        elif isinstance(content, list):
            for block in content:
                # Assistant text blocks only — skip tool_use / tool_result noise.
                if isinstance(block, dict) and block.get("type") == "text":
                    t = (block.get("text") or "").strip()
                    if t:
                        texts.append(t)
    if not texts:
        return ""
    narrative = "\n\n".join(texts[-max_messages:]).strip()
    if len(narrative) > max_chars:
        narrative = "…" + narrative[-max_chars:]
    return narrative


def _annotate_possibly_done(
    pending_items: list[dict[str, Any]],
    recent_tasks: list[dict[str, Any]],
    recent_commits: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Flag pending sprint items whose keywords match a recent task or commit.

    Adds ``possibly_done=True`` and ``possibly_done_matches`` (list of
    matching descriptions) to any item with ≥3 keyword matches in the last
    20 tasks or last 10 commits.  Items are not modified otherwise.

    23e79944 — the overlap threshold is 3 (raised from 2) and Meridian-domain
    high-frequency terms (:data:`_MERIDIAN_STOP_WORDS`) are excluded from the
    keyword sets, so items sharing only generic words like "session"/"handoff"/
    "notes"/"decisions" with a large task log no longer trigger false positives.
    """
    # Build a corpus of recent activity texts
    corpus: list[str] = [
        str(t.get("description") or "") for t in (recent_tasks or [])[:20]
    ]
    if recent_commits:
        corpus.extend(str(c) for c in recent_commits[:10])

    for item in pending_items:
        title = item.get("title") or ""
        kws = _extract_keywords(title, _MERIDIAN_STOP_WORDS)
        if len(kws) < 3:
            continue
        matches = []
        for text in corpus:
            text_kws = _extract_keywords(text, _MERIDIAN_STOP_WORDS)
            if len(kws & text_kws) >= 3:
                matches.append(text[:120])
        if matches:
            item["possibly_done"] = True
            item["possibly_done_matches"] = matches[:3]
    return pending_items


async def _annotate_touches_files(
    db: aiosqlite.Connection,
    project_id: str,
    pending_items: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Auto-set touches_resources on pending items whose title keywords match
    recently changed files (git diff --name-only HEAD~3). Persists the match to
    the DB so start_session file_warnings can reference it. Safe to skip on error.

    78ebc812 — the write previously targeted a ``touches_files`` column that does
    NOT exist on this schema (only the SQLite legacy migration ever added it; the
    Postgres side has ``touches_resources`` only, so the UPDATE failed silently on
    prod under the guarded except). Matched paths are now stored as typed
    ``touches_resources`` identifiers (``inferred:file:<path>``) — the canonical,
    conflict-aware format read by get_sprint_items / get_parallelizable_groups —
    reusing the existing column (no new column / migration)."""
    import subprocess  # noqa: PLC0415
    try:
        result = subprocess.run(
            ["git", "diff", "--name-only", "HEAD~3"],
            capture_output=True, text=True, timeout=5
        )
        changed_files = [f.strip() for f in result.stdout.splitlines() if f.strip()]
    except Exception:  # noqa: BLE001
        return pending_items
    if not changed_files:
        return pending_items

    for item in pending_items:
        if item.get("touches_resources"):
            continue
        title_kws = _extract_keywords(item.get("title") or "")
        if len(title_kws) < 2:
            continue
        matched = []
        for fpath in changed_files:
            # Match on filename stem and any path segment keyword
            fname = os.path.basename(fpath)
            fname_stem = os.path.splitext(fname)[0]
            path_kws = _extract_keywords(fpath.replace("/", " ").replace(".", " "))
            if fname_stem and fname_stem in title_kws:
                matched.append(fpath)
            elif len(title_kws & path_kws) >= 2:
                matched.append(fpath)
        if matched:
            # Store as typed, provenance-marked resource ids so the value round-
            # trips through parse/serialize_touches_resources and participates in
            # conflict detection. serialize_touches_resources normalizes + dedupes.
            inferred = [f"inferred:file:{fpath}" for fpath in matched[:10]]
            touches = db_module.serialize_touches_resources(inferred)
            if not touches:
                continue
            item["touches_resources"] = touches
            try:
                async with db.execute(
                    "UPDATE sprint_items SET touches_resources = ? "
                    "WHERE id = ? AND project_id = ?",
                    (touches, item["id"], project_id),
                ) as _:
                    pass
                await db.commit()
            except Exception:  # noqa: BLE001
                pass
    return pending_items


