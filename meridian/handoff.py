# 4cfaecc2 — wireable resolver seam. handoff.py deliberately does NOT import the
# tunnel/routing layer (that would be a layering violation and an import cycle),
# so the server registers a resolver at startup that maps a project_id to a
# tunnel-backed graph searcher. Absent a registered resolver, enrichment stays a
# no-op (the historical behaviour), and the resolver — like every enrichment hop —
# is fully guarded so it can never break the mandatory handoff.
_GRAPH_SEARCHER_RESOLVER: Callable[[str], Callable[[str], Any] | None] | None = None


def set_graph_searcher_resolver(
    resolver: Callable[[str], Callable[[str], Any] | None] | None,
) -> None:
    """Register (or clear with None) the project_id -> graph-searcher resolver.

    Called once by the server layer, which has the tenant/tunnel context that
    handoff.py must not import directly.
    """
    global _GRAPH_SEARCHER_RESOLVER
    _GRAPH_SEARCHER_RESOLVER = resolver


def _resolve_graph_searcher(
    project_id: str,
) -> Callable[[str], Any] | None:
    """Return a code-graph search callable for ``project_id`` or None.

    Consults the resolver registered via :func:`set_graph_searcher_resolver`
    (wired to the tunnel code-intel slot by the server). When no resolver is
    registered — or it raises/returns None — enrichment degrades to no pointers.
    Tests and in-process deployments can also inject a searcher directly via the
    ``graph_searcher`` argument to ``generate_handoff``, which takes precedence.
    """
    if _GRAPH_SEARCHER_RESOLVER is None:
        return None
    try:
        return _GRAPH_SEARCHER_RESOLVER(project_id)
    except Exception:  # noqa: BLE001 — resolver must never break the handoff
        return None


def _coerce_match_list(result: Any) -> list[Any]:
    """Normalise a graph-search result into a list of match dicts."""
    if result is None:
        return []
    if isinstance(result, list):
        return result
    if isinstance(result, dict):
        for key in ("results", "matches", "nodes", "hits", "items"):
            val = result.get(key)
            if isinstance(val, list):
                return val
        # A single match dict (file/name keys) is itself one result.
        return [result]
    return []


def _normalize_code_pointer(match: Any) -> dict[str, str] | None:
    """Coerce a single graph-search match into a {file, function, qualified_name}
    pointer. Returns None when the match has no usable location info."""
    if not isinstance(match, dict):
        return None
    file = (
        match.get("file")
        or match.get("file_path")
        or match.get("path")
        or ""
    )
    function = (
        match.get("function")
        or match.get("name")
        or match.get("symbol")
        or ""
    )
    qualified = (
        match.get("qualified_name")
        or match.get("qualified")
        or match.get("fqn")
        or function
    )
    file = str(file).strip()
    function = str(function).strip()
    qualified = str(qualified).strip()
    if not (file or function or qualified):
        return None
    return {
        "file": file,
        "function": function,
        "qualified_name": qualified,
    }


def _code_pointer_query(title: str, kws: set[str]) -> str:
    """Build a stable, readable graph-search query from an item title."""
    return " ".join(
        w for w in re.findall(r"[a-z0-9_/-]{3,}", title.lower()) if w in kws
    ) or title.strip()


def _touches_resource_terms(item: dict[str, Any]) -> list[str]:
    """182468a6 — extract search terms from an item's declared touches_resources.

    Identifiers look like ``inferred:file:meridian/handler.py`` or
    ``file:meridian/handoff.py:_render_starter_handoff``; strip the optional
    ``inferred:`` prefix and the type token (``file:``/``db:``/``mcp_tool:``/…)
    and keep the path (+ any trailing symbol) as a precise search term. Tolerant
    of the JSON-string, list, and bare-string storage shapes; never raises.
    """
    raw = item.get("touches_resources")
    ids: list[Any] = []
    if isinstance(raw, str) and raw.strip():
        try:
            parsed = json.loads(raw)
            ids = parsed if isinstance(parsed, list) else [raw]
        except Exception:  # noqa: BLE001
            ids = [raw]
    elif isinstance(raw, list):
        ids = raw
    terms: list[str] = []
    for ident in ids:
        s = str(ident).strip()
        if not s:
            continue
        if s.startswith("inferred:"):
            s = s[len("inferred:"):]
        # drop a single leading type token (file:/db:/mcp_tool:/route:/pypi:/github:)
        head, sep, tail = s.partition(":")
        term = (tail if sep and head.isalpha() else s).strip()
        if term:
            terms.append(term)
    return terms


def build_declared_symbol_targets(item: dict[str, Any]) -> list[dict[str, Any]]:
    """691f4e1c — build DURABLE ``symbol`` pointer targets from an item's DECLARED
    ``touches_resources`` (no code index required), so add/update-time prospecting can
    persist a real, retrievable pointer rather than a one-shot ``code_context`` hint.

    Shared source of truth reused by the handler's add/update prospecting path so the
    ``symbol``-selector shape isn't duplicated across modules (this file already owns
    the touches_resources parsing + the graph-match ``_normalize_code_pointer`` shape).

    The server can't reach the code graph (04a15d3f — it's behind the executor's
    tunnel), so an exact line ``range`` can't be resolved at write time. A W3C
    ``symbol`` selector carrying the declared ``qualified_name`` is the tunnel-free
    equivalent: stored verbatim now, best-matched against the graph LATER at resolve
    time by ``pointers._resolve_symbol`` once the tunnel is up. Only ``symbol:<qn>``
    entries yield a target — a bare ``file:``/``inferred:file:`` touch has no exact
    symbol location tunnel-free, and fabricating one would attach a misleading,
    unresolvable pointer. Symbols are paired with the first declared file as the
    target ``uri`` when present, else a ``symbol:`` URI. Never raises.
    """
    raw = item.get("touches_resources")
    ids: list[Any] = []
    if isinstance(raw, str) and raw.strip():
        try:
            parsed = json.loads(raw)
            ids = parsed if isinstance(parsed, list) else [raw]
        except Exception:  # noqa: BLE001
            ids = [raw]
    elif isinstance(raw, list):
        ids = raw
    files: list[str] = []
    # Each symbol carries its own file scope: a ``symbol:<path>::<name>`` id (63b030a6)
    # names both the file (uri) and the symbol (qualified_name).
    symbols: list[tuple[str, str | None]] = []
    for ident in ids:
        s = str(ident or "").strip()
        if not s:
            continue
        if s.startswith("inferred:"):
            s = s[len("inferred:"):].strip()
        if s.startswith("symbol:"):
            # ``symbol:<path>::<name>`` — split off the ``::<name>`` symbol scope; the
            # bare symbol name is the query the code-graph resolver best-matches on.
            body = s[len("symbol:"):].strip()
            if not body:
                continue
            path, sep, name = body.partition("::")
            if sep and name.strip():
                symbols.append((name.strip(), path.strip() or None))
            elif body:
                # No ``::`` scope — treat the whole tail as the qualified_name.
                symbols.append((body, None))
        elif s.startswith("file:"):
            fp = s[len("file:"):].strip()
            if fp:
                files.append(fp)
    if not symbols:
        return []
    default_file = files[0] if files else None
    targets: list[dict[str, Any]] = []
    seen: set[str] = set()
    for qn, sym_file in symbols:
        if qn in seen:
            continue
        seen.add(qn)
        file_for_uri = sym_file or default_file
        targets.append({
            "uri": f"file:{file_for_uri}" if file_for_uri else f"symbol:{qn}",
            "selector": {"type": "symbol", "qualified_name": qn},
        })
    return targets


def _prospect_query(item: dict[str, Any], title: str, kws: set[str]) -> str:
    """182468a6 — prefer the item's declared touches_resources (real file/symbol
    identifiers) as the search target; fall back to stopword-stripped title
    keywords only when no resources are declared. Declared resources are far more
    precise than title words, and let an item with a terse title still prospect."""
    terms = _touches_resource_terms(item)
    if terms:
        return " ".join(terms)
    return _code_pointer_query(title, kws)


# 10bfe531 — handoff prospecting is source_type-aware, not code-only. Keyword
# signals (title + tags) map an item to the pointer source_type that fits it. `code`
# is the default and the one prospector wired in production today; docs/citation/
# experiment are reached through an injected prospector seam (2976e168 primitive).
_POINTER_SOURCE_KEYWORDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("citation", ("zotero", "citation", "bibliograph", "arxiv", " doi", "\\cite", "paper", "related work")),
    ("docs", ("docx", "ooxml", "latex", "\\section", "document structure", "document outline", ".doc")),
    ("experiment", ("benchmark", "experiment", "ablation", "dataset", "evaluation", " eval", "finding", "reproduc")),
)


def _infer_pointer_source_type(item: dict[str, Any]) -> str:
    """10bfe531 — classify the pointer source_type that best fits a sprint item so
    handoff prospecting isn't code-only. Cheap keyword scan over title + tags;
    defaults to ``code`` (the overwhelmingly common case in this repo). Returns one of
    ``citation`` | ``docs`` | ``experiment`` | ``code``."""
    text = ((item.get("title") or "") + " " + str(item.get("tags") or "")).lower()
    for stype, needles in _POINTER_SOURCE_KEYWORDS:
        if any(n in text for n in needles):
            return stype
    return "code"


def _build_generic_pointer(source_type: str, match: Any) -> dict[str, Any] | None:
    """10bfe531 — turn a non-code prospector match into a validated generic pointer
    (2976e168 primitive). Accepts a ready-made ``{targets: [...]}`` shape or a single
    ``{uri, selector}`` target. Returns a validated pointer, or None when it can't be
    made valid — best-effort, never raises."""
    if not isinstance(match, dict):
        return None
    from .pointers import validate_pointer, PointerValidationError  # noqa: PLC0415
    if isinstance(match.get("targets"), list) and match["targets"]:
        candidate: dict[str, Any] = {"source_type": source_type, "targets": match["targets"]}
    elif match.get("uri") and match.get("selector"):
        candidate = {
            "source_type": source_type,
            "targets": [{"uri": match["uri"], "selector": match["selector"]}],
        }
    else:
        return None
    if match.get("label"):
        candidate["label"] = str(match["label"])
    try:
        return validate_pointer(candidate)
    except PointerValidationError:
        return None


async def _annotate_code_pointers(
    pending_items: list[dict[str, Any]],
    searcher: Callable[[str], Any] | None,
    *,
    prospectors: dict[str, Callable[[str], Any]] | None = None,
    reprospect: bool = False,
) -> list[dict[str, Any]]:
    """Prospect a pointer for each NON-MANUAL pending item, by fitting source_type.

    10bfe531 — generalized beyond code: each item is classified via
    :func:`_infer_pointer_source_type` to ``code`` / ``docs`` / ``citation`` /
    ``experiment``. ``code`` items are searched with ``searcher`` (the code-graph
    search) and get a ``code_pointers`` entry, exactly as before. Non-code items are
    searched with an injected ``prospectors[source_type]`` callable and get a
    validated generic ``pointers`` entry (2976e168 primitive). The classification is
    recorded on each prospected item as ``pointer_source_type``. The function name is
    retained for the existing call site and the monkeypatch tests.

    MANUAL/human items are skipped entirely — prospecting a maintainer todo (e.g.
    "form an LLC") only attaches misleading pointers. A non-code item whose backend
    isn't wired is left un-pointered rather than falling back to a code search, which
    would attach a spurious code pointer to a paper/citation/experiment item.

    ``searcher`` / prospectors may be sync or coroutine callables; results may be a
    list, a ``{results|matches: [...]}`` dict, or a single match dict.

    Robustness contract: this must NEVER raise. All failures degrade to no pointer for
    that item — generate_handoff is mandatory and breaking it is unacceptable.
    """
    registry: dict[str, Callable[[str], Any]] = dict(prospectors or {})
    if searcher is not None:
        registry.setdefault("code", searcher)
    if not registry:
        return pending_items
    # 182468a6 — surface the cap instead of silently dropping items past it: any
    # non-manual item beyond the enrichment cap is marked skipped_cap so the caller
    # / handoff can tell "not prospected for capacity" apart from "no match found".
    for item in pending_items[_MAX_ENRICHED_ITEMS:]:
        if not _is_manual_sprint_item(item):
            item.setdefault("prospect_status", "skipped_cap")
    for item in pending_items[:_MAX_ENRICHED_ITEMS]:
        if _is_manual_sprint_item(item):
            item["prospect_status"] = "skipped_manual"  # 10bfe531 — never prospect
            continue
        # 182468a6 — a prior pointer is kept by default, but reprospect=True re-runs
        # the search so a stale/bad guess can be corrected instead of frozen forever.
        if (item.get("code_pointers") or item.get("pointers")) and not reprospect:
            item.setdefault("prospect_status", "cached")
            continue
        title = item.get("title") or ""
        kws = _extract_keywords(title)
        stype = _infer_pointer_source_type(item)
        item["pointer_source_type"] = stype
        prospector = registry.get(stype)
        if prospector is None:
            item["prospect_status"] = "no_backend"  # don't mis-prospect
            continue
        # 182468a6 — target the search at declared touches_resources when present
        # (far more precise than stopword-stripped title keywords).
        query = _prospect_query(item, title, kws)
        if not query:
            item["prospect_status"] = "no_query"
            continue
        try:
            result = prospector(query)
            if hasattr(result, "__await__"):
                result = await result  # type: ignore[misc]
            matches = _coerce_match_list(result)
            if not matches:
                item["prospect_status"] = "no_match"
                continue
            # 182468a6 — validate matches: take the FIRST that yields a usable
            # pointer rather than blindly trusting matches[0] (which may lack any
            # location info while a later match has it). When reprospecting, clear
            # any prior pointer of the other kind so the item can't carry both.
            if stype == "code":
                pointer = next(
                    (p for p in (_normalize_code_pointer(m) for m in matches) if p),
                    None,
                )
                if pointer:
                    item["code_pointers"] = [pointer]
                    if reprospect:
                        item.pop("pointers", None)
                    item["prospect_status"] = "prospected"
                else:
                    item["prospect_status"] = "no_valid_match"
            else:
                gp = next(
                    (g for g in (_build_generic_pointer(stype, m) for m in matches) if g),
                    None,
                )
                if gp:
                    item["pointers"] = [gp]
                    if reprospect:
                        item.pop("code_pointers", None)
                    item["prospect_status"] = "prospected"
                else:
                    item["prospect_status"] = "no_valid_match"
        except Exception:  # noqa: BLE001 — enrichment is best-effort, never fatal
            item["prospect_status"] = "error"
            continue
    return pending_items


