"""Write Meridian's local MCP servers into Claude Desktop and Codex configs.

One definition of each server lives here. ``plan`` shows what would change,
``apply --yes`` writes it, and ``remove --yes`` takes out only the entries
Meridian owns. Paths are resolved on the machine that runs the setup, so a new
environment needs this command instead of hand-edited per-repo files.

Entries that Meridian does not own are never touched. Each write makes a
timestamped backup first. A rewritten Codex TOML file is parsed again, and
unowned tables are compared before anything is written.

CLI: ``python -m meridian.client_setup {plan,apply,remove}
[--client claude-desktop|codex|all] [--yes]``. Paths can be overridden with
``--claude-config`` and ``--codex-config`` (used by tests).
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
import time
import tomllib
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

SERENA_PACKAGE = "serena-agent==1.5.3"
CLIENTS = ("claude-desktop", "codex")

# Server names each client already uses, so existing tool names stay the same.
CLIENT_SERVER_NAMES = {
    "claude-desktop": {
        "codebase": "codebase-memory-mcp",
        "serena": "meridian-extract",
        "docs": "meridian-docs",
        "outputs": "meridian-outputs",
        "search": "meridian-search",
    },
    "codex": {
        "codebase": "codebase-memory-mcp",
        "serena": "serena-local",
        "docs": "meridian-docs",
        "outputs": "meridian-outputs",
        "search": "meridian-search",
    },
}
SERENA_CONTEXT = {"claude-desktop": "claude-code", "codex": "codex"}

MANAGED_BEGIN = "# >>> meridian managed mcp servers (generated by meridian.client_setup; do not edit) >>>"
MANAGED_END = "# <<< meridian managed mcp servers <<<"
# Keys of an owned server's main table that setup rewrites. Any other key in an
# owned table (for example a timeout) makes setup refuse, instead of dropping it.
_MANAGED_MAIN_KEYS = frozenset({"command", "args", "env", "enabled"})
_TOML_HEADER = re.compile(r"^\s*\[(?!\[)\s*([^\]]+?)\s*\]\s*(?:#.*)?$")
_BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")


class SetupError(RuntimeError):
    """A config cannot be read, a required executable is missing, or a write would be unsafe."""


@dataclass
class ServerSpec:
    name: str
    command: str
    args: list[str]
    env: dict[str, str] = field(default_factory=dict)

    def json_entry(self) -> dict:
        entry: dict = {"command": self.command, "args": list(self.args)}
        if self.env:
            entry["env"] = dict(self.env)
        return entry


def find_executable(name: str, fallbacks: tuple[Path, ...] = ()) -> str:
    found = shutil.which(name)
    if found:
        return found
    for candidate in fallbacks:
        if candidate.is_file():
            return str(candidate)
    raise SetupError(f"{name} was not found on PATH or in ~/.local/bin")


def build_specs(
    client: str,
    repo_root: Path,
    *,
    python_exe: str,
    uvx: str,
    codebase: str,
) -> list[ServerSpec]:
    """The Meridian server set for one client, with paths resolved on this machine."""
    if client not in CLIENT_SERVER_NAMES:
        raise SetupError(f"unknown client: {client}")
    names = CLIENT_SERVER_NAMES[client]
    repo = Path(repo_root)
    docs_dir = repo / "extensions" / "meridian-docs"
    outputs_dir = repo / "extensions" / "meridian-outputs"
    for required in (docs_dir, outputs_dir, repo / "meridian" / "code_search.py"):
        if not required.exists():
            raise SetupError(f"expected Meridian source is missing: {required}")
    return [
        ServerSpec(names["codebase"], codebase, ["--ui=false"]),
        ServerSpec(
            names["serena"],
            uvx,
            [
                "--python", "3.12", "--from", SERENA_PACKAGE, "serena", "start-mcp-server",
                "--context", SERENA_CONTEXT[client],
                "--enable-web-dashboard", "false",
                "--enable-gui-log-window", "false",
                "--open-web-dashboard", "false",
            ],
        ),
        ServerSpec(names["docs"], uvx, ["--from", str(docs_dir), "meridian-docs-mcp"]),
        ServerSpec(names["outputs"], uvx, ["--from", str(outputs_dir), "meridian-outputs-mcp"]),
        ServerSpec(
            names["search"],
            python_exe,
            ["-m", "meridian.code_search"],
            {"PYTHONPATH": str(repo)},
        ),
    ]


def owned_names(client: str) -> set[str]:
    return set(CLIENT_SERVER_NAMES[client].values())


def default_claude_desktop_config(env=None) -> Path:
    source = os.environ if env is None else env
    if sys.platform == "win32":
        appdata = str(source.get("APPDATA") or "").strip()
        base = Path(appdata) if appdata else Path.home() / "AppData" / "Roaming"
        return base / "Claude" / "claude_desktop_config.json"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "Claude" / "claude_desktop_config.json"
    return Path.home() / ".config" / "Claude" / "claude_desktop_config.json"


def default_codex_config(env=None) -> Path:
    source = os.environ if env is None else env
    home = str(source.get("CODEX_HOME") or "").strip()
    return (Path(home) if home else Path.home() / ".codex") / "config.toml"


def _backup(path: Path) -> str | None:
    if not path.exists():
        return None
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = path.with_name(f"{path.name}.meridian-backup-{stamp}")
    shutil.copy2(path, backup)
    return str(backup)


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.meridian-tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)


# ---- Claude Desktop (JSON) -------------------------------------------------

def _load_claude_document(path: Path) -> dict:
    if not path.exists():
        return {}
    raw = path.read_text(encoding="utf-8")
    if not raw.strip():
        return {}
    try:
        document = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise SetupError(f"{path} is not valid JSON; refusing to rewrite it ({exc})") from exc
    if not isinstance(document, dict):
        raise SetupError(f"{path} does not hold a JSON object; refusing to rewrite it")
    return document


def plan_claude_desktop(path: Path, specs: list[ServerSpec] | None, owned: set[str]) -> dict:
    """Compute the new document. ``specs=None`` plans a removal of owned entries."""
    document = _load_claude_document(path)
    current = document.get("mcpServers") or {}
    if not isinstance(current, dict):
        raise SetupError(f"{path} has a non-object mcpServers value; refusing to rewrite it")
    wanted = {s.name: s.json_entry() for s in specs} if specs is not None else {}
    merged: dict = {}
    for name, value in current.items():
        if name not in owned:
            merged[name] = value
        elif name in wanted:
            merged[name] = wanted.pop(name)
    for name, value in wanted.items():
        merged[name] = value
    new_document = dict(document)
    if merged or "mcpServers" in document:
        new_document["mcpServers"] = merged
    changes = _changes(current, merged, owned)
    return {
        "path": str(path),
        "changes": changes,
        "document": new_document,
        "unchanged": new_document == document,
    }


def write_claude_desktop(plan: dict) -> str | None:
    path = Path(plan["path"])
    backup = _backup(path)
    _atomic_write(path, json.dumps(plan["document"], indent=2, ensure_ascii=False) + "\n")
    return backup


def _changes(old: dict, new: dict, owned: set[str]) -> dict:
    added = sorted(n for n in owned if n in new and n not in old)
    changed = sorted(n for n in owned if n in new and n in old and new[n] != old[n])
    removed = sorted(n for n in owned if n in old and n not in new)
    unchanged = sorted(n for n in owned if n in new and n in old and new[n] == old[n])
    return {"added": added, "changed": changed, "removed": removed, "unchanged": unchanged}


# ---- Codex (TOML, managed block) ------------------------------------------

def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _toml_key(key: str) -> str:
    return key if _BARE_KEY.fullmatch(key) else _toml_string(key)


def _strip_managed_block(lines: list[str]) -> list[str]:
    out: list[str] = []
    inside = False
    for line in lines:
        stripped = line.strip()
        if stripped == MANAGED_BEGIN:
            inside = True
            continue
        if inside:
            if stripped == MANAGED_END:
                inside = False
            continue
        out.append(line)
    return out


def _extract_owned_tables(lines: list[str], owned: set[str]) -> tuple[list[str], dict[str, list[str]]]:
    """Remove the main ``[mcp_servers.<name>]`` table bodies of owned servers.

    Sub-tables stay where they are. Keys in an owned main table that setup does
    not manage (``cwd``, timeouts) are returned per server so they carry over.
    """
    targets = {f"mcp_servers.{name}": name for name in owned}
    kept: list[str] = []
    preserved: dict[str, list[str]] = {name: [] for name in owned}
    current: str | None = None
    for line in lines:
        match = _TOML_HEADER.match(line)
        if match:
            current = targets.get(match.group(1).replace(" ", ""))
            if current is None:
                kept.append(line)
            continue
        if current is None:
            kept.append(line)
            continue
        key = line.split("=", 1)[0].strip() if "=" in line else ""
        if key and key not in _MANAGED_MAIN_KEYS and not key.startswith("#"):
            preserved[current].append(line.rstrip())
    return kept, preserved


def _render_block(specs: list[ServerSpec], preserved: dict[str, list[str]] | None = None) -> list[str]:
    lines = [MANAGED_BEGIN]
    for spec in specs:
        lines.append(f"[mcp_servers.{spec.name}]")
        lines.append(f"command = {_toml_string(spec.command)}")
        lines.append("args = [" + ", ".join(_toml_string(a) for a in spec.args) + "]")
        if spec.env:
            pairs = ", ".join(f"{_toml_key(k)} = {_toml_string(v)}" for k, v in spec.env.items())
            lines.append("env = { " + pairs + " }")
        lines.extend((preserved or {}).get(spec.name, []))
        lines.append("")
    lines.append(MANAGED_END)
    return lines


def _trim_trailing_blank(lines: list[str]) -> list[str]:
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines


def render_codex(old_text: str, specs: list[ServerSpec] | None, owned: set[str]) -> str:
    base, preserved = _extract_owned_tables(_strip_managed_block(old_text.splitlines()), owned)
    base = _trim_trailing_blank(base)
    if specs is not None:
        block = _render_block(specs, preserved)
        base = base + ([""] if base else []) + block
    return "\n".join(base) + "\n" if base else ""


def _tomllib_loads(text: str, label: str) -> dict:
    try:
        return tomllib.loads(text) if text.strip() else {}
    except tomllib.TOMLDecodeError as exc:
        raise SetupError(f"{label} is not valid TOML; refusing to rewrite it ({exc})") from exc


def validate_codex(old_text: str, new_text: str, owned: set[str]) -> None:
    """Raise unless the new TOML parses and every unowned part is unchanged."""
    old = _tomllib_loads(old_text, "existing Codex config")
    new = _tomllib_loads(new_text, "rendered Codex config")
    for key in set(old) | set(new):
        if key == "mcp_servers":
            continue
        if old.get(key) != new.get(key):
            raise SetupError(f"rendering would change unowned top-level key '{key}'; aborting")
    old_servers = old.get("mcp_servers", {}) or {}
    new_servers = new.get("mcp_servers", {}) or {}
    for name in set(old_servers) | set(new_servers):
        if name in owned:
            old_rest = {k: v for k, v in (old_servers.get(name) or {}).items()
                        if k not in _MANAGED_MAIN_KEYS}
            new_rest = {k: v for k, v in (new_servers.get(name) or {}).items()
                        if k not in _MANAGED_MAIN_KEYS}
            if old_rest != new_rest:
                raise SetupError(
                    f"owned server '{name}' has settings setup does not manage "
                    f"({', '.join(sorted(old_rest))}); remove them or move them to a sub-table, then re-run"
                )
            continue
        if old_servers.get(name) != new_servers.get(name):
            raise SetupError(f"rendering would change unowned MCP server '{name}'; aborting")


def plan_codex(path: Path, specs: list[ServerSpec] | None, owned: set[str]) -> dict:
    old_text = path.read_text(encoding="utf-8") if path.exists() else ""
    new_text = render_codex(old_text, specs, owned)
    validate_codex(old_text, new_text, owned)
    old_servers = (_tomllib_loads(old_text, "existing Codex config").get("mcp_servers") or {})
    new_servers = (_tomllib_loads(new_text, "rendered Codex config").get("mcp_servers") or {})
    # Owned servers that were switched off get switched back on; say so in the plan.
    re_enabled = sorted(
        n for n in owned
        if specs is not None and isinstance(old_servers.get(n), dict)
        and old_servers[n].get("enabled") is False
    )
    return {
        "path": str(path),
        "changes": _changes(
            {k: v for k, v in old_servers.items() if k in owned},
            {k: v for k, v in new_servers.items() if k in owned},
            owned,
        ),
        "re_enabled": re_enabled,
        "text": new_text,
        "unchanged": new_text == old_text,
    }


def write_codex(plan: dict) -> str | None:
    path = Path(plan["path"])
    backup = _backup(path)
    _atomic_write(path, plan["text"])
    return backup


# ---- orchestration ---------------------------------------------------------

def _summary(client: str, plan: dict, action: str, backup: str | None) -> dict:
    return {
        "client": client,
        "path": plan["path"],
        "action": action,
        "changes": plan["changes"],
        "re_enabled": plan.get("re_enabled", []),
        "backup": backup,
        "restart_required": action in ("written", "removed"),
    }


def run_setup(
    mode: str,
    *,
    clients: tuple[str, ...],
    write: bool,
    claude_path: Path,
    codex_path: Path,
    repo_root: Path,
    python_exe: str,
    uvx: str,
    codebase: str,
) -> list[dict]:
    """Plan or apply (``mode="apply"``) or remove (``mode="remove"``) Meridian's entries."""
    results: list[dict] = []
    for client in clients:
        owned = owned_names(client)
        target = claude_path if client == "claude-desktop" else codex_path
        specs = None
        if mode == "apply":
            specs = build_specs(client, repo_root, python_exe=python_exe, uvx=uvx, codebase=codebase)
        if client == "claude-desktop":
            plan = plan_claude_desktop(target, specs, owned)
            writer = write_claude_desktop
        else:
            plan = plan_codex(target, specs, owned)
            writer = write_codex
        if plan["unchanged"]:
            results.append(_summary(client, plan, "unchanged", None))
            continue
        if not write:
            results.append(_summary(client, plan, "would_write" if mode == "apply" else "would_remove", None))
            continue
        backup = writer(plan)
        results.append(_summary(client, plan, "written" if mode == "apply" else "removed", backup))
    return results


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m meridian.client_setup",
        description="Set up Meridian's local MCP servers in Claude Desktop and Codex.",
    )
    parser.add_argument("mode", choices=("plan", "apply", "remove"), nargs="?", default="plan")
    parser.add_argument("--client", choices=(*CLIENTS, "all"), default="all")
    parser.add_argument("--claude-config", type=Path, default=None)
    parser.add_argument("--codex-config", type=Path, default=None)
    parser.add_argument("--yes", action="store_true", help="Write the change. Without it, only plan.")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    clients = CLIENTS if args.client == "all" else (args.client,)
    write = args.yes and args.mode != "plan"
    mode = "remove" if args.mode == "remove" else "apply"
    repo_root = Path(__file__).resolve().parents[1]
    try:
        uvx = find_executable("uvx", (Path.home() / ".local" / "bin" / "uvx.exe",
                                      Path.home() / ".local" / "bin" / "uvx")) if mode == "apply" else ""
        codebase = find_executable("codebase-memory-mcp", (
            Path.home() / ".local" / "bin" / "codebase-memory-mcp.exe",
            Path.home() / ".local" / "bin" / "codebase-memory-mcp",
        )) if mode == "apply" else ""
        results = run_setup(
            mode,
            clients=clients,
            write=write,
            claude_path=args.claude_config or default_claude_desktop_config(),
            codex_path=args.codex_config or default_codex_config(),
            repo_root=repo_root,
            python_exe=sys.executable,
            uvx=uvx,
            codebase=codebase,
        )
    except SetupError as exc:
        print(json.dumps({"error": str(exc)}, indent=2), file=sys.stderr)
        return 1
    print(json.dumps({"results": results, "wrote": write}, indent=2))
    if args.mode == "plan" or not write:
        print("Nothing written. Re-run with --yes to apply.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
